const path=require('node:path'),assert=require('node:assert/strict');
const {chromium}=require(path.join(process.env.APPDATA,'npm/node_modules/@playwright/cli/node_modules/playwright'));
(async()=>{
 const browser=await chromium.launch({channel:'chrome',headless:true});
 try{
  const page=await browser.newPage({viewport:{width:1440,height:960}}),errors=[];
  page.on('pageerror',e=>errors.push(e.message));page.setDefaultTimeout(6000);
  const dialog=()=>page.locator('#dialog'),settings=()=>page.locator('.query-links').getByRole('button',{name:/设置/}).click();
  const order=()=>dialog().locator('tbody tr').evaluateAll(rows=>rows.map(row=>row.dataset.field));
  const visible=()=>page.locator('.boiler-advanced .field>label').allTextContents();
  const save=()=>dialog().getByRole('button',{name:'保存',exact:true}).click();
  const schema=type=>type==='installation'?'V2InstallationSchema':'V2PipelineSchema';
  const results={};
  for(const type of ['installation','pipeline']){
   await page.goto('http://127.0.0.1:8020/#'+type);
   await page.locator('#query-form').getByRole('button',{name:/高级查询/}).click();
   const definitions=await page.evaluate(name=>window[name].advanced.map(f=>({key:f.key,label:f.label})),schema(type));
   const defaults=definitions.map(f=>f.key);
   const retainedKey=type==='installation'?'equipmentCode':'registrationCode';
   const tableHeaders=await page.locator('.table-panel th').allTextContents();
   await page.locator('#query-form [name=' + retainedKey + ']').fill('DEMO');
   await settings();
   assert.equal(await page.locator('#dialog-title').innerText(),'查询条件自定义字段');
   assert.equal(await dialog().locator('.settings-grid').count(),0);
   assert.deepEqual(await order(),defaults);
   assert(await dialog().locator('tbody tr').first().getByRole('button',{name:/上移/}).isDisabled());
   assert(await dialog().locator('tbody tr').last().getByRole('button',{name:/下移/}).isDisabled());
   await dialog().locator('tbody tr').first().getByRole('button',{name:/下移/}).click();
   assert.deepEqual((await visible()).slice(0,2),[definitions[1].label,definitions[0].label]);
   await dialog().locator('tbody tr').nth(1).getByRole('button',{name:/上移/}).click();
   assert.deepEqual(await order(),defaults);
   await dialog().locator('tr[data-field="'+defaults[2]+'"]').dragTo(dialog().locator('tr[data-field="'+defaults[0]+'"]'));
   const reordered=await order();
   assert.equal(reordered[0],defaults[2]);
   const hiddenKey=defaults[1],hidden=definitions[1].label;
   await dialog().locator('tr[data-field="'+hiddenKey+'"] input[type=checkbox]').uncheck();
   assert(!(await visible()).includes(hidden));
   await dialog().locator('tbody tr').first().getByRole('button',{name:/下移/}).click();
   assert(!(await dialog().locator('tr[data-field="'+hiddenKey+'"] input[type=checkbox]').isChecked()));
   const saved=await order();
   await save();
   assert.deepEqual(await page.locator('.table-panel th').allTextContents(),tableHeaders);
   assert.equal(await page.locator('#query-form [name=' + retainedKey + ']').inputValue(),'DEMO');
   assert.deepEqual(await visible(),saved.filter(k=>k!==hiddenKey).map(k=>definitions.find(f=>f.key===k).label));
   await settings();assert.deepEqual(await order(),saved);
   await page.locator('#dialog-close').click();
   await page.reload();
   await page.locator('#query-form').getByRole('button',{name:/高级查询/}).click();
   assert.deepEqual(await visible(),saved.filter(k=>k!==hiddenKey).map(k=>definitions.find(f=>f.key===k).label));
   await settings();assert.deepEqual(await order(),saved);
   assert(!(await dialog().locator('tr[data-field="'+hiddenKey+'"] input').isChecked()));
   await dialog().locator('tr[data-field="'+hiddenKey+'"] input').check();await save();
   assert.equal((await visible()).length,defaults.length);
   // A draft is previewed while open and discarded by closing without saving.
   await settings();await dialog().locator('tbody tr').first().getByRole('button',{name:/下移/}).click();
   await page.locator('#dialog-close').click();await settings();assert.deepEqual(await order(),saved);
   await page.locator('#dialog-close').click();
   results[type]=saved;
   console.log('PASS',type,'arrows, drag, boundaries, live visibility, save, reopen, reload and draft cancel');
  }
  await page.goto('http://127.0.0.1:8020/#installation');await settings();assert.deepEqual(await order(),results.installation);
  await dialog().getByRole('button',{name:'还原初始配置'}).click();await save();
  await page.reload();await settings();
  assert.deepEqual(await order(),await page.evaluate(()=>V2InstallationSchema.advanced.map(f=>f.key)));
  await page.locator('#dialog-close').click();
  await page.goto('http://127.0.0.1:8020/#pipeline');await settings();assert.deepEqual(await order(),results.pipeline);
  await page.locator('#dialog-close').click();
  await page.locator('#query-form').getByRole('button',{name:/高级查询/}).click();
  await page.locator('[name=inspectionProblems]').selectOption('腐蚀');
  await page.locator('[name=managementProblems]').selectOption('质量管理体系');
  await page.locator('[name=registrationCode]').fill('DEMO');
  await settings();
  await dialog().locator('tr[data-field=inspectionProblems] input[type=checkbox]').uncheck();
  await save();
  assert.equal(await page.locator('[name=inspectionProblems],[name=managementProblems]').count(),0);
  assert.equal(await page.locator('[name=registrationCode]').inputValue(),'DEMO');
  await page.locator('#query-form button[type=submit]').click();
  assert.equal(await page.locator('.count-total').innerText(),'8');
  await settings();await dialog().locator('tr[data-field=inspectionProblems] input[type=checkbox]').check();await save();
  assert.equal(await page.locator('[name=managementProblems]').inputValue(),'');
  assert.deepEqual(errors,[]);
  console.log('PASS independent module storage and persistent default restore');
 }finally{await browser.close()}
})().catch(e=>{console.error(e);process.exitCode=1});
